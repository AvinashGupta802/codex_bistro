function item(id, name, shortName, category, price, accent, icon, aliases) {
  return {
    id,
    name,
    shortName,
    category,
    price,
    accent,
    icon,
    image: foodImageUrl(name),
    tags: [category, icon.replace("-", " ")],
    aliases
  };
}

function foodImageUrl(name) {
  return `https://loremflickr.com/640/480/${encodeURIComponent(`${name},food,restaurant`)}`;
}

export function findMenuItem(text) {
  const normalized = normalize(text);
  return menu
    .map((entry) => {
      const alias = entry.aliases.find((candidate) => normalized.includes(normalize(candidate)));
      return alias ? { item: entry, score: alias.length } : null;
    })
    .filter(Boolean)
    .sort((a, b) => b.score - a.score)[0]?.item ?? null;
}

export function normalize(value) {
  return String(value).toLowerCase().replace(/[^a-z0-9\s-]/g, " ").replace(/\s+/g, " ").trim();
}
